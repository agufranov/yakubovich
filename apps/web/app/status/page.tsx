/**
 * Страница для заказчика: что решили и что сделано.
 *
 * Живет на сайте, а не в docs/, потому что заказчик смотрит выкладку, а не
 * репозиторий. Цифры считаются из базы на момент сборки — документ не должен
 * расходиться с тем, что реально собрано.
 *
 * Язык деловой, без внутренней кухни: коннекторы, robots.txt и разбор верстки
 * остаются в docs/. Здесь только то, что меняет решения заказчика.
 */
import type { Metadata } from 'next';
import Link from 'next/link';
import { KIND_LABELS, formatMoney, lotSlug, readSchedule } from '@bankrot/shared';
import { getStore } from '@/lib/data';

export const metadata: Metadata = { title: 'Статус проекта' };

const SOURCE_GROUPS: [RegExp, string, string][] = [
  [
    /^gis-torgi$/,
    'ГИС Торги (государственные)',
    'Арестованное имущество приставов и приватизация. Открытые данные, смежный товар для того же покупателя',
  ],
  [
    /^itender-/,
    'Банкротные площадки семейства iTender',
    '14 площадок работают на одном движке — их обслуживает один и тот же код',
  ],
  [
    /^etp-mets$/,
    'МЭТС',
    'Крупная банкротная площадка. Характеристики машины полями, график снижения цены, стороны торгов',
  ],
];

function sourceGroup(code: string): { name: string; note: string } {
  const hit = SOURCE_GROUPS.find(([re]) => re.test(code));
  return hit ? { name: hit[1], note: hit[2] } : { name: code, note: '' };
}

export default function StatusPage() {
  const lots = getStore().loadLots();

  const byGroup = new Map<string, { name: string; note: string; count: number }>();
  for (const lot of lots) {
    const g = sourceGroup(lot.sourceCode);
    const cur = byGroup.get(g.name) ?? { ...g, count: 0 };
    cur.count++;
    byGroup.set(g.name, cur);
  }
  const groups = [...byGroup.values()].sort((a, b) => b.count - a.count);

  const vehicles = lots.filter((l) => l.kind === 'vehicle');
  const withVin = lots.filter((l) => l.attributes.some((a) => a.key === 'vin'));
  const withSchedule = lots.filter((l) => (l.pricePeriods?.length ?? 0) > 0);
  const withParties = lots.filter((l) => (l.parties?.length ?? 0) > 0);
  const bankruptcy = lots.filter((l) => l.legalBasis === 'bankruptcy_127fz');

  // самый показательный лот: чем длиннее график, тем нагляднее механика падения цены
  const showcase = [...withSchedule].sort(
    (a, b) => (b.pricePeriods?.length ?? 0) - (a.pricePeriods?.length ?? 0),
  )[0];
  const showcaseFloor = showcase ? readSchedule(showcase.pricePeriods).floor : undefined;

  const num = (n: number): string => n.toLocaleString('ru-RU');

  return (
    <main className="page status-page">
      <h1 style={{ fontSize: 24, marginTop: 0 }}>Статус проекта</h1>
      <p className="lead">
        На чём договорились, что уже работает и что нужно решить, чтобы двигаться дальше.
        Все цифры — из базы на момент этой выкладки, а не из презентации.
      </p>

      <section className="panel">
        <h2>Что решили</h2>
        <dl className="decisions">
          <dt>Начинаем с банкротных автомобилей</dt>
          <dd>
            Машина — единственный класс имущества, где рыночную цену вообще можно посчитать:
            есть VIN и тысячи сопоставимых объявлений. Для квартиры такой базы сравнения нет.
          </dd>

          <dt>Автомобили — первый шаг, а не весь продукт</dt>
          <dd>
            Вид имущества и основание торгов (банкротство, приставы, приватизация) заложены как
            признаки лота, а не как отдельные продукты. Добавить потом квартиры или спецтехнику —
            это настройка, а не переписывание.
          </dd>

          <dt>Объект, лот и торги — разные вещи</dt>
          <dd>
            Одна и та же машина выставляется по нескольку раз: повторные торги, затем публичное
            предложение со снижением цены. Мы храним это как историю одного объекта, а не как
            несвязанные объявления. Не заложить сразу — потом переразбирать весь архив.
          </dd>

          <dt>Ничего не удаляем</dt>
          <dd>
            Площадки стирают завершённые торги со своих сайтов. Наш архив — то, что нельзя
            будет собрать задним числом ни за какие деньги, и он копится с первого дня.
          </dd>

          <dt>Что сознательно отложили</dt>
          <dd>
            Расчёт рыночной цены и инвестиционной оценки, недвижимость, коммерческие торги,
            партнёрские сервисы. Это ограничение функциональности, а не модели: место под них
            в данных предусмотрено, чтобы потом не ломать сделанное.
          </dd>
        </dl>
      </section>

      <section className="panel">
        <h2>Что сделано</h2>
        <p>
          Собрано <strong>{num(lots.length)}</strong> лотов: из них{' '}
          <strong>{num(bankruptcy.length)}</strong> банкротных и{' '}
          <strong>{num(vehicles.length)}</strong> — транспорт. У{' '}
          <strong>{num(withVin.length)}</strong> лотов есть VIN — это те, по которым в будущем
          можно будет считать рыночную цену.
        </p>

        <table className="attr-table">
          <tbody>
            {groups.map((g) => (
              <tr key={g.name}>
                <td>
                  <strong>{g.name}</strong>
                  {g.note && <div className="muted">{g.note}</div>}
                </td>
                <td style={{ whiteSpace: 'nowrap' }}>{num(g.count)} лотов</td>
              </tr>
            ))}
          </tbody>
        </table>

        <h3>МЭТС — площадка, ради которой это делалось</h3>
        <p>
          Проверено запросами к самой площадке: у неё <strong>3 104</strong> банкротных лота в
          категории «Легковой автомобиль», и это не считая коммерческого транспорта,
          спецтехники и мототехники. Объёма для первого этапа достаточно.
        </p>
        <p>
          Подключение сделано и работает; идёт первый полный проход по каталогу площадки —
          поэтому число лотов МЭТС в таблице выше пока меньше, чем у неё на сайте. Дальше
          обновления забираются ежедневно и только по изменившимся лотам.
        </p>
        <p>Что МЭТС отдаёт такого, чего нет у других проверенных площадок:</p>
        <ul className="ticks">
          <li>
            <strong>Характеристики машины отдельными полями</strong> — марка, модель, год,
            пробег, мощность, коробка, привод и VIN. Не текстом в описании, который пришлось бы
            разбирать и угадывать.
          </li>
          <li>
            <strong>График снижения цены таблицей.</strong> Это главная механика публичного
            предложения: цена падает по расписанию, и весь вопрос — когда заходить. Мы получаем
            график готовым, а не вычитываем из текста условий. Уже разобран у{' '}
            {num(withSchedule.length)} лотов.
          </li>
          <li>
            <strong>Стороны торгов.</strong> Должник, арбитражный управляющий, организатор и
            залоговый кредитор — отдельными полями, с ИНН. Разобраны у {num(withParties.length)}{' '}
            лотов.
          </li>
        </ul>

        <h3>Сущности: должник и арбитражный управляющий</h3>
        <p>
          Это не строчки в описании, а отдельные записи с ИНН и номером дела о банкротстве.
          Практический смысл: с карточки лота можно одним щелчком получить все лоты этого
          управляющего или всё имущество, распродаваемое по одному делу. У должников-физлиц
          площадка показывает ещё и СНИЛС — его мы принципиально не берём.
        </p>
      </section>

      {showcase && (
        <section className="panel">
          <h2>Как это выглядит на лоте</h2>
          <p>
            Живой пример из базы:{' '}
            <Link href={`/lot/${lotSlug(showcase.id)}`}>{showcase.title}</Link>
          </p>
          <table className="attr-table">
            <tbody>
              <tr>
                <td>Начальная цена</td>
                <td>{formatMoney(showcase.priceStart, showcase.currency) ?? '—'}</td>
              </tr>
              <tr>
                <td>Цена дойдёт до</td>
                <td>{formatMoney(showcaseFloor?.price, showcase.currency) ?? '—'}</td>
              </tr>
              <tr>
                <td>Шагов снижения в графике</td>
                <td>{showcase.pricePeriods?.length}</td>
              </tr>
              <tr>
                <td>Вид имущества</td>
                <td>{KIND_LABELS[showcase.kind]}</td>
              </tr>
            </tbody>
          </table>
          <p className="muted">
            На карточке виден весь график с подсветкой текущего периода, цена на сегодня, дата и
            размер ближайшего снижения — и стороны торгов.
          </p>
        </section>
      )}

      <section className="panel">
        <h2>Что дальше</h2>
        <ol className="next-steps">
          <li>
            <strong>Полный сбор по МЭТС.</strong> Довести первый проход до конца, дальше —
            ежедневные обновления. После этого будет видна реальная картина по машинам: сколько
            активных, в каких регионах, по каким ценам.
          </li>
          <li>
            <strong>Остальные крупные площадки</strong> — Сбербанк-АСТ, Российский аукционный
            дом, Фабрикант. Порядок подключения — по количеству лотов, а не по известности
            названия.
          </li>
          <li>
            <strong>Склейка одного объекта между площадками по VIN.</strong> Одна машина может
            выставляться дважды и попасть к нам из двух источников. Первый шаг — точное
            совпадение VIN, без догадок.
          </li>
          <li>
            <strong>Рыночная цена.</strong> Самая дорогая часть, и она упирается в вопрос ниже.
          </li>
        </ol>
      </section>

      <section className="panel">
        <h2>Что нужно от вас</h2>
        <p>Три вопроса. Без ответов мы либо стоим, либо начинаем сочинять за вас.</p>
        <dl className="decisions">
          <dt>Откуда берём рыночные цены на машины</dt>
          <dd>
            Без цены рынка нет ни выгоды, ни оценки — только «лот за 500 тысяч» без ответа, много
            это или мало. Авито запрещает сбор своими правилами и активно ему противодействует;
            Дром и auto.ru мягче; Автотека платная, но легальная и даёт историю по VIN. Нужно
            ваше решение: бюджет или доступ.
          </dd>

          <dt>Из чего складываются риск, ликвидность и оценка вложения</dt>
          <dd>
            Это считается из данных, но по чьим-то правилам. Правила должны быть ваши — из
            опыта. Если мы придумаем их сами, сайт будет уверенно показывать цифры, за которыми
            ничего не стоит.
          </dd>

          <dt>Показываем ли имя должника-физлица</dt>
          <dd>
            Сведения открыты в государственном реестре, но выводить конкретного человека в
            поисковую выдачу по его имени — отдельное действие и отдельный риск. До запуска
            нужна консультация юриста. Технически мы готовы к обоим вариантам.
          </dd>
        </dl>
      </section>

      <p className="footnote">
        Мы не проводим торги и не принимаем задатки: сайт показывает лоты и уводит на
        официальную площадку, где и происходит сделка.
      </p>
    </main>
  );
}
