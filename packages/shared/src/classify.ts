/**
 * Классификация вида имущества по свободному тексту (docs/05: сначала правила,
 * потом LLM). Общая для всех источников: у ГИС Торги это фолбэк после точных
 * кодов категорий, у ЭТП банкротства — основной путь (там категория приходит
 * текстом классификатора ЕФРСБ).
 */
import type { LotKind } from './types';

export function classifyKind(text: string): LotKind {
  const hay = text.toLowerCase();
  if (/автомоб|транспорт|легков|грузов|прицеп|мотоцикл|спецтехн|самоход|судно|катер|самолет|воздушн/.test(hay)) return 'vehicle';
  if (/земельн|земли|участок/.test(hay)) return 'land';
  if (/квартир|жил|помещен|здани|недвиж|дом|гараж|машино-?мест|сооружен|строительств/.test(hay)) return 'realty';
  if (/оборудован|станок|станк|техник|инструмент|электрон/.test(hay)) return 'equipment';
  if (/дебиторск|права требован/.test(hay)) return 'receivable';
  if (/доля в уставн|акци|предприят|бизнес/.test(hay)) return 'business';
  return 'other';
}
